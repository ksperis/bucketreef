_FONT_REGULAR = "BucketReefVera"
_FONT_BOLD = "BucketReefVera-Bold"
_DISCLAIMER = "Technical cost statement generated by BucketReef. Not a legal commercial invoice."


def _register_fonts() -> None:
    fonts_dir = Path(reportlab.__file__).resolve().parent / "fonts"
    if _FONT_REGULAR not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont(_FONT_REGULAR, fonts_dir / "Vera.ttf"))
    if _FONT_BOLD not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont(_FONT_BOLD, fonts_dir / "VeraBd.ttf"))


_register_fonts()


@dataclass(frozen=True)
class _PdfLine:
    subject: str
    endpoint: str
    basis: str
    storage_quantity: str
    rate_plan: str
    amount: str


@dataclass(frozen=True)
class _PdfStatement:
    public_id: str
    entity_name: str
    entity_code: str | None
    entity_external_id: str | None
    period_start: date
    period_end: date
    currency: str
    total: Decimal
    member_count: int
    storage_coverage: Decimal
    usage_coverage: Decimal
    quota_coverage: Decimal | None
    estimation_mode: str
    estimation_reason: str | None
    estimation_requested_by_email: str | None
    estimation_methods: tuple[str, ...]
    finalized_at: datetime
    lines: tuple[_PdfLine, ...]


def _decimal_text(value: Decimal | None, *, places: int = 3) -> str:
    if value is None:
        return "-"
    return f"{value:.{places}f}"


def _money(value: Decimal, currency: str) -> str:
    return f"{value:.2f} {currency}"


def _rate_plan(snapshot) -> str:
    resolution = snapshot.rate_resolution
    if resolution.status != "resolved":
        return resolution.status.replace("_", " ").title()
    return resolution.rate_plan_name or (resolution.layer or "resolved").replace("_", " ").title()


def _statement_from_item(item: BillingStatementItem) -> _PdfStatement:
    if item.status != "finalized" or item.finalized_at is None:
        raise ValueError("Billing Statement PDF is available only for finalized statements")
    estimation_methods: set[str] = set()
    for line in item.lines:
        estimation = line.snapshot.estimation
        if estimation is None:
            continue
        if estimation.usage_extrapolation_factor is not None:
            estimation_methods.add("Usage extrapolated from observed monthly activity")
        if estimation.storage_method == "observed_daily_average":
            estimation_methods.add("Storage estimated from observed daily average")
        elif estimation.storage_method == "allocated_quota_average":
            estimation_methods.add("Allocated quota estimated from observed quota average")
    return _PdfStatement(
        public_id=item.public_id,
        entity_name=item.billing_entity_name,
        entity_code=item.billing_entity_code,
        entity_external_id=item.billing_entity_external_id,
        period_start=item.period_start,
        period_end=item.period_end,
        currency=item.currency,
        total=item.total,
        member_count=item.member_count,
        storage_coverage=item.coverage.storage_coverage_ratio,
        usage_coverage=item.coverage.usage_coverage_ratio,
        quota_coverage=item.coverage.quota_coverage_ratio,
        estimation_mode=item.estimation_mode,
        estimation_reason=item.estimation_reason,
        estimation_requested_by_email=item.estimation_requested_by_email,
        estimation_methods=tuple(sorted(estimation_methods)),
        finalized_at=item.finalized_at,
        lines=tuple(
            _PdfLine(
                subject=line.snapshot.subject_name,
                endpoint=line.snapshot.storage_endpoint_name,
                basis=(line.snapshot.storage_charge_basis or "-").replace("_", " ").title(),
                storage_quantity=(
                    f"{_decimal_text(line.snapshot.priced_storage_quantity.quantity_gib_month)} GiB-month"
                    if line.snapshot.priced_storage_quantity is not None
                    else "-"
                ),
                rate_plan=_rate_plan(line.snapshot),
                amount=(
                    _money(line.snapshot.amounts.total_cost, line.currency)
                    if line.snapshot.amounts.total_cost is not None
                    else "-"
                ),
            )
            for line in item.lines
        ),
    )


