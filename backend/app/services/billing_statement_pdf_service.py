class BillingStatementPdfService:
    """Render a human-readable cost statement from an immutable Billing snapshot."""

    @classmethod
    def render_statement(
        cls,
        item: BillingStatementItem,
        settings: BillingStatementPdfSettings,
    ) -> bytes:
        return cls._render(_statement_from_item(item), settings)

    @classmethod
    def render_preview(cls, settings: BillingStatementPdfSettings) -> bytes:
        return cls._render(_preview_statement(), settings)

    @staticmethod
    def _paragraph(text: str | None, style: ParagraphStyle) -> Paragraph:
        safe = escape(text or "-").replace("\n", "<br/>")
        return Paragraph(safe, style)

    @classmethod
    def _render(cls, statement: _PdfStatement, settings: BillingStatementPdfSettings) -> bytes:
        output = BytesIO()
        accent = colors.HexColor(settings.accent_color)
        styles = getSampleStyleSheet()
        body = ParagraphStyle(
            "BillingBody",
            parent=styles["BodyText"],
            fontName=_FONT_REGULAR,
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#1f2937"),
        )
        muted = ParagraphStyle(
            "BillingMuted",
            parent=body,
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#6b7280"),
        )
        heading = ParagraphStyle(
            "BillingHeading",
            parent=body,
            fontName=_FONT_BOLD,
            fontSize=11,
            leading=14,
            textColor=colors.HexColor("#111827"),
            spaceBefore=5 * mm,
            spaceAfter=2 * mm,
        )
        title = ParagraphStyle(
            "BillingTitle",
            parent=body,
            fontName=_FONT_BOLD,
            fontSize=19,
            leading=22,
            textColor=accent,
        )
        right = ParagraphStyle("BillingRight", parent=body, alignment=TA_RIGHT)
        table_header = ParagraphStyle(
            "BillingTableHeader",
            parent=body,
            fontName=_FONT_BOLD,
            fontSize=7.3,
            leading=9,
            textColor=colors.white,
        )
        table_body = ParagraphStyle("BillingTableBody", parent=body, fontSize=7.2, leading=9)

        doc = SimpleDocTemplate(
            output,
            pagesize=A4,
            leftMargin=18 * mm,
            rightMargin=18 * mm,
            topMargin=16 * mm,
            bottomMargin=28 * mm,
            title=f"Billing Statement {statement.public_id}",
            author=settings.organization_name,
            subject="BucketReef Billing Statement",
            invariant=1,
        )
        story = []

        logo = None
        if settings.logo_data_url:
            encoded = settings.logo_data_url.split(",", 1)[1]
            logo = Image(BytesIO(base64.b64decode(encoded)), width=30 * mm, height=14 * mm, kind="proportional")

        header_left = logo if logo is not None else cls._paragraph(settings.organization_name, heading)
        header_right = [cls._paragraph("Billing Statement", title), cls._paragraph(statement.public_id, right)]
        header = Table([[header_left, header_right]], colWidths=[68 * mm, 106 * mm], hAlign="LEFT")
        header.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("ALIGN", (1, 0), (1, 0), "RIGHT"),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4 * mm),
            ("LINEBELOW", (0, 0), (-1, -1), 1.4, accent),
        ]))
        story.append(header)
        if logo is not None:
            story.append(cls._paragraph(settings.organization_name, heading))
        if settings.organization_details:
            story.append(cls._paragraph(settings.organization_details, muted))

        story.append(Spacer(1, 4 * mm))
        meta_rows = [
            ["Billing Entity", statement.entity_name, "Period", f"{statement.period_start.isoformat()} - {statement.period_end.isoformat()}"],
            ["Entity code", statement.entity_code or "-", "Currency", statement.currency],
            ["External ID", statement.entity_external_id or "-", "Finalized", statement.finalized_at.isoformat()],
            ["Members", str(statement.member_count), "Total", _money(statement.total, statement.currency)],
        ]
        meta = Table(
            [[cls._paragraph(str(cell), body) for cell in row] for row in meta_rows],
            colWidths=[26 * mm, 61 * mm, 23 * mm, 64 * mm],
            hAlign="LEFT",
        )
        meta.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f3f4f6")),
            ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#f3f4f6")),
            ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#d1d5db")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(meta)

        if statement.estimation_mode == "coverage_extrapolation":
            story.append(cls._paragraph("Estimated statement — incomplete source coverage", heading))
            estimation_text = "; ".join(statement.estimation_methods) or "Coverage extrapolation applied"
            if statement.estimation_reason:
                estimation_text += f". Reason: {statement.estimation_reason}"
            if statement.estimation_requested_by_email:
                estimation_text += f". Requested by: {statement.estimation_requested_by_email}"
            story.append(cls._paragraph(estimation_text, body))

        coverage = (
            f"Storage {_decimal_text(statement.storage_coverage * 100, places=0)}%  ·  "
            f"Usage {_decimal_text(statement.usage_coverage * 100, places=0)}%"
        )
        if statement.quota_coverage is not None:
            coverage += f"  ·  Quota {_decimal_text(statement.quota_coverage * 100, places=0)}%"
        story.append(cls._paragraph("Coverage", heading))
        story.append(cls._paragraph(coverage, body))

        if settings.statement_note:
            story.append(cls._paragraph("Statement note", heading))
            story.append(cls._paragraph(settings.statement_note, body))

        story.append(cls._paragraph("Cost detail", heading))
        line_rows = [[
            cls._paragraph("Subject", table_header),
            cls._paragraph("Endpoint", table_header),
            cls._paragraph("Storage basis", table_header),
            cls._paragraph("Storage", table_header),
            cls._paragraph("Rate Plan", table_header),
            cls._paragraph("Amount", table_header),
        ]]
        for line in statement.lines:
            line_rows.append([
                cls._paragraph(line.subject, table_body),
                cls._paragraph(line.endpoint, table_body),
                cls._paragraph(line.basis, table_body),
                cls._paragraph(line.storage_quantity, table_body),
                cls._paragraph(line.rate_plan, table_body),
                cls._paragraph(line.amount, table_body),
            ])
        line_table = Table(
            line_rows,
            colWidths=[35 * mm, 30 * mm, 28 * mm, 27 * mm, 29 * mm, 25 * mm],
            repeatRows=1,
            hAlign="LEFT",
        )
        line_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), accent),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#d1d5db")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f9fafb")]),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(line_table)
        story.append(Spacer(1, 4 * mm))
        total_table = Table(
            [[cls._paragraph("Finalized total", heading), cls._paragraph(_money(statement.total, statement.currency), right)]],
            colWidths=[120 * mm, 54 * mm],
        )
        total_table.setStyle(TableStyle([
            ("LINEABOVE", (0, 0), (-1, 0), 1.2, accent),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        story.append(total_table)

        footer_lines = [_DISCLAIMER]
        if settings.footer_text:
            footer_lines.insert(0, settings.footer_text)
        footer = cls._paragraph(
            "\n".join(footer_lines),
            ParagraphStyle(
                "BillingFooter",
                parent=muted,
                fontSize=6.5,
                leading=8,
            ),
        )

        def page(canvas_obj: canvas.Canvas, _doc) -> None:
            canvas_obj.saveState()
            canvas_obj.setTitle(f"Billing Statement {statement.public_id}")
            canvas_obj.setAuthor(settings.organization_name)
            canvas_obj.setSubject("BucketReef Billing Statement")
            canvas_obj.setFont(_FONT_REGULAR, 7)
            canvas_obj.setFillColor(colors.HexColor("#6b7280"))
            footer_width = A4[0] - (18 * mm) - (45 * mm)
            _, footer_height = footer.wrap(footer_width, 22 * mm)
            footer.drawOn(canvas_obj, 18 * mm, 6 * mm)
            canvas_obj.drawRightString(A4[0] - 18 * mm, 6 * mm + min(footer_height, 22 * mm), f"Page {canvas_obj.getPageNumber()}")
            canvas_obj.restoreState()

        canvas_factory = partial(canvas.Canvas, invariant=1, pageCompression=1)
        doc.build(story, onFirstPage=page, onLaterPages=page, canvasmaker=canvas_factory)
        return output.getvalue()
