export type GroupsMessageKey = keyof typeof groupsMessage;
type GroupsText = (key: GroupsMessageKey, values?: Record<string, string | number>) => string;

export function useGroupsI18n() {
  const { locale, t } = useI18n();
  const text: GroupsText = useCallback(
    (key, values) => t(groupsMessage[key]).replace(/\{(\w+)\}/g, (match, name: string) => String(values?.[name] ?? match)),
    [t],
  );
  return { locale, text };
}
