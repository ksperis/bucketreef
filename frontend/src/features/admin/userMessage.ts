type UserMessageKey = keyof typeof userMessage;
type UserText = (key: UserMessageKey, values?: Record<string, string | number>) => string;

export function useUserI18n() {
  const { locale, t } = useI18n();
  const text: UserText = useCallback(
    (key, values) => interpolateText(t(userMessage[key]), values),
    [t],
  );
  return { locale, text };
}
